#!/usr/bin/env node
/**
 * Writes src/data/imageSizes.ts and the narrow variants that back srcset.
 *
 * An <img> with no dimensions has zero height until its bytes arrive, so the
 * page reflows as each one loads. Giving the browser the real width and height
 * lets it reserve the box up front, which is what keeps Cumulative Layout Shift
 * at zero. Sizes are read from the files themselves rather than hand-written so
 * they cannot drift; run this after adding or replacing images.
 *
 * Wide images also get a 480px-wide sibling. A project thumbnail rendered into a
 * 350px column was downloading its full 900px original on a phone; offering the
 * smaller file through srcset lets the browser pick the one it will actually
 * display.
 */
const VARIANT_WIDTH = 480;
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import sharp from 'sharp';

const ROOT = 'public/img';

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path, out);
    else if (/\.(webp|avif|png|jpe?g|gif)$/i.test(entry.name)) out.push(path);
  }
  return out;
}

const entries = [];
for (const file of walk(ROOT).sort()) {
  if (file.includes(`-${VARIANT_WIDTH}w.`)) continue;
  const { width, height } = await sharp(file).metadata();
  const url = `/img/${relative(ROOT, file).split(/[\\/]/).join('/')}`;

  // Only worth a second file when the original is meaningfully wider than the
  // variant; otherwise the browser gains nothing for an extra request.
  const wantsVariant = width > VARIANT_WIDTH * 1.3;
  if (wantsVariant) {
    const variant = file.replace(/\.(\w+)$/, `-${VARIANT_WIDTH}w.$1`);
    if (!existsSync(variant)) await sharp(file).resize({ width: VARIANT_WIDTH }).webp({ quality: 82 }).toFile(variant);
  }
  entries.push(`  "${url}": [${width}, ${height}, ${wantsVariant}],`);
}

writeFileSync(
  'src/data/imageSizes.ts',
  `// Generated by scripts/gen-image-sizes.mjs — do not edit by hand.\n` +
    `// Intrinsic [width, height] per image, used to reserve layout space.\n` +
    `// [width, height, hasNarrowVariant]\n` +
    `export const imageSizes: Record<string, [number, number, boolean]> = {\n${entries.join('\n')}\n};\n` +
    `\nexport const VARIANT_WIDTH = ${VARIANT_WIDTH};\n`,
);
console.log(`[sizes]  ${entries.length} images measured, ${entries.filter((e) => e.endsWith('true],')).length} with a ${VARIANT_WIDTH}w variant`);
