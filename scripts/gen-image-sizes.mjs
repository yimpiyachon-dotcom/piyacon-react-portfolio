#!/usr/bin/env node
/**
 * Writes src/data/imageSizes.ts and the narrow variants that back srcset.
 *
 * An <img> with no dimensions has zero height until its bytes arrive, so the
 * page reflows as each one loads. Giving the browser the real width and height
 * lets it reserve the box up front, which is what keeps Cumulative Layout Shift
 * at zero. Sizes are read from the files themselves rather than hand-written so
 * they cannot drift; run this after adding or replacing images.
 *
 * Wide images also get smaller siblings for srcset. A single 480px tier was not
 * enough once full-resolution walkthrough boards landed: a phone needs roughly
 * 1,000 device pixels for a full-width board, so it skipped the 480 file and
 * pulled the 2,560px original every time. The middle tier is what that gap
 * needed — measured at 3.69 MB before it existed.
 */
const VARIANT_WIDTHS = [480, 1200];
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import sharp from 'sharp';

const ROOT = 'public/img';

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path, out);
    else if (/\.(webp|avif|png|jpe?g|gif)$/i.test(entry.name)) out.push(path);
  }
  return out;
}

const entries = [];
for (const file of walk(ROOT).sort()) {
  if (/-\d+w\.\w+$/.test(file)) continue;
  const { width, height } = await sharp(file).metadata();
  const url = `/img/${relative(ROOT, file).split(/[\\/]/).join('/')}`;

  // A tier only earns its extra request when the original is meaningfully
  // wider than it; otherwise the browser gains nothing by switching files.
  const tiers = VARIANT_WIDTHS.filter((w) => width > w * 1.3);
  for (const w of tiers) {
    const variant = file.replace(/\.(\w+)$/, `-${w}w.$1`);
    if (!existsSync(variant)) await sharp(file).resize({ width: w }).webp({ quality: 82 }).toFile(variant);
  }
  entries.push(`  "${url}": [${width}, ${height}, [${tiers.join(', ')}]],`);
}

writeFileSync(
  'src/data/imageSizes.ts',
  `// Generated by scripts/gen-image-sizes.mjs — do not edit by hand.\n` +
    `// Intrinsic [width, height] per image, used to reserve layout space.\n` +
    `// [width, height, widths of the generated smaller variants]\n` +
    `export const imageSizes: Record<string, [number, number, number[]]> = {\n${entries.join('\n')}\n};\n`,
);
console.log(
  `[sizes]  ${entries.length} images measured, ` +
    VARIANT_WIDTHS.map((w) => `${entries.filter((e) => e.includes(`${w},`) || e.includes(`${w}]`)).length} at ${w}w`).join(', '),
);
